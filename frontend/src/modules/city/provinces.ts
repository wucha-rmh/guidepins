/** 取六位代码的前两位作为省份代码；格式不符时返回空串，调用方据此忽略该地市。 */
export function provinceCodeOf(code: string): string {
  return /^[0-9]{2}/.test(code) ? code.slice(0, 2) : ''
}

/** 省份显示名；字典里没登记的代码直接回落成「省份 XX」，避免下拉框出现空选项。 */
export function provinceNameOf(code: string): string {
  return provinceNames[code] ?? `省份 ${code}`
}
